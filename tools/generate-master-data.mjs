import { createHash } from 'node:crypto'
import { readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const registryPath = resolve(root, 'shared/contracts/master-data.json')
const outputs = {
  csharp: resolve(
    root,
    'api/src/Advertified.Commercial.Domain/Generated/MasterDataCodes.g.cs',
  ),
  typescript: resolve(root, 'web/src/generated/master-data-codes.ts'),
  python: resolve(root, 'agent-runtime/master_data_codes.py'),
}
const checkOnly = process.argv.includes('--check')

const source = await readFile(registryPath, 'utf8')
const registry = JSON.parse(source)
const sourceHash = createHash('sha256').update(source).digest('hex')

function words(value) {
  return value
    .replace(/([a-z0-9])([A-Z])/g, '$1 $2')
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
}

function pascal(value) {
  const identifier = words(value)
    .map((word) => word[0].toUpperCase() + word.slice(1).toLowerCase())
    .join('')
  return /^\d/.test(identifier) ? `Code${identifier}` : identifier
}

function camel(value) {
  const identifier = pascal(value)
  return identifier[0].toLowerCase() + identifier.slice(1)
}

function csharpLiteral(value) {
  return JSON.stringify(value)
}

function renderCsharp() {
  const lines = [
    '// <auto-generated />',
    `// source: shared/contracts/master-data.json; source-sha256: ${sourceHash}`,
    'using Advertified.Commercial.Domain.Governance;',
    '',
    'namespace Advertified.Commercial.Domain.MasterData;',
    '',
    'public static class MasterDataCodes',
    '{',
    `    public const string RegistryVersion = ${csharpLiteral(registry.registryVersion)};`,
  ]
  for (const [collection, items] of Object.entries(registry.collections)) {
    lines.push('', `    public static class ${pascal(collection)}`, '    {')
    lines.push(`        public const string Collection = ${csharpLiteral(collection)};`)
    for (const item of items) {
      lines.push(`        public const string ${pascal(item.code)} = ${csharpLiteral(item.code)};`)
    }
    lines.push('    }')
  }
  lines.push('}', '')

  const typed = new Map([
    ['lifecycleStatuses', 'LifecycleStatusCode'],
    ['permissions', 'PermissionCode'],
    ['roles', 'RoleCode'],
    ['currencies', 'CurrencyCode'],
    ['vatStatuses', 'VatStatusCode'],
    ['contactPurposes', 'ContactPurposeCode'],
    ['commercialResourceTypes', 'ResourceTypeCode'],
    ['commercialActions', 'ActionCode'],
    ['commercialEventTypes', 'EventTypeCode'],
  ])
  lines.push('public static class MasterDataReferences', '{')
  for (const [collection, type] of typed) {
    const items = registry.collections[collection]
    if (!items) continue
    const group = pascal(collection)
    lines.push(`    public static class ${group}`, '    {')
    for (const item of items) {
      const name = pascal(item.code)
      lines.push(
        `        public static readonly ${type} ${name} = new(MasterDataCodes.${group}.${name});`,
      )
    }
    lines.push('    }', '')
  }
  lines.push('}', '')
  return `${lines.join('\n')}\n`
}

function renderTypescript() {
  const lines = [
    '// Generated from shared/contracts/master-data.json. Do not edit.',
    `// source-sha256: ${sourceHash}`,
    'export const masterDataCodes = {',
  ]
  for (const [collection, items] of Object.entries(registry.collections)) {
    lines.push(`  ${camel(collection)}: {`)
    for (const item of items) {
      lines.push(`    ${camel(item.code)}: ${JSON.stringify(item.code)},`)
    }
    lines.push('  },')
  }
  lines.push('} as const', '', 'export const masterDataDefinitions = {')
  for (const [collection, items] of Object.entries(registry.collections)) {
    lines.push(`  ${camel(collection)}: ${JSON.stringify(items)},`)
  }
  lines.push('} as const', '')
  return `${lines.join('\n')}\n`
}

function renderPython() {
  const lines = [
    '# Generated from shared/contracts/master-data.json. Do not edit.',
    `# source-sha256: ${sourceHash}`,
    'from enum import StrEnum',
    '',
    `REGISTRY_VERSION = ${JSON.stringify(registry.registryVersion)}`,
  ]
  for (const [collection, items] of Object.entries(registry.collections)) {
    lines.push('', `class ${pascal(collection)}(StrEnum):`)
    for (const item of items) {
      const member = words(item.code).join('_').toUpperCase()
      const safeMember = /^\d/.test(member) ? `CODE_${member}` : member
      lines.push(`    ${safeMember} = ${JSON.stringify(item.code)}`)
    }
  }
  lines.push('')
  return `${lines.join('\n')}\n`
}

async function synchronize(path, expected) {
  if (checkOnly) {
    const actual = await readFile(path, 'utf8').catch(() => '')
    if (actual !== expected) {
      throw new Error(`Generated master-data projection is stale: ${path}`)
    }
    return
  }
  await writeFile(path, expected, 'utf8')
}

await Promise.all([
  synchronize(outputs.csharp, renderCsharp()),
  synchronize(outputs.typescript, renderTypescript()),
  synchronize(outputs.python, renderPython()),
])

process.stdout.write(
  `${checkOnly ? 'Verified' : 'Generated'} master-data projections for registry ${registry.registryVersion}.\n`,
)
